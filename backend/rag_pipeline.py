"""
EvidenceBot - RAG Pipeline Orchestrator
=======================================
Coordinates the end-to-end Retrieval-Augmented Generation (RAG) architecture:
1. Question Reception
2. PubMed Literature Retrieval (ESearch + EFetch)
3. Abstract Filtering & Deduplication
4. Text Cleaning & Chunking with Metadata Provenance
5. Dense Vector Embedding Generation (SentenceTransformers)
6. FAISS Vector Database Indexing
7. Cosine Similarity Retrieval
8. Irrelevance Filtering & Abstention Guard (Similarity Threshold)
9. Grounded Multi-Paper Synthesis
10. Comprehensive Citation Audit & Missing Citation Detection
11. Claim-Level Evidence Verification
"""

from dataclasses import dataclass, field
from typing import Dict, Any, List, Optional
import os
import logging

from utils import config
from backend.pubmed import PubMedRetriever, PaperMetadata
from backend.preprocessing import chunk_papers, EvidenceChunk
from backend.vector_store import FaissVectorStore
from backend.evidence_checker import (
    evaluate_evidence_sufficiency,
    verify_answer_claims,
    evaluate_abstention_triggers,
    AbstentionReport,
)
from backend.citation_checker import (
    verify_citations,
    validate_citations_comprehensive,
    CitationAuditReport,
)
from backend.llm import generate_biomedical_answer

logger = logging.getLogger(__name__)


@dataclass
class RAGPipelineResult:
    """
    Complete audit payload generated by the EvidenceBot RAG pipeline.
    Preserves all provenance from original PubMed records down to synthesized citations.
    """
    status: str                                  # 'success', 'abstained', or 'error'
    question: str                                # User's original biomedical inquiry
    answer: str                                  # Synthesized response or abstention advisory
    confidence: str                              # 'High', 'Moderate', 'Preliminary', or 'Insufficient'
    max_score: float                             # Highest cosine similarity score achieved
    threshold_used: float                        # Confidence threshold enforced
    is_abstention: bool                          # True if synthesis was safely withheld
    reason: str                                  # Explanation of evidence sufficiency verdict
    provider: str                                # LLM or Extractive engine used
    verified_pmids: List[str] = field(default_factory=list)      # PMIDs cited and confirmed authentic
    hallucinated_pmids: List[str] = field(default_factory=list)  # Any PMIDs detected that were not in sources
    papers: List[PaperMetadata] = field(default_factory=list)    # Retrieved PubMed publications
    chunks: List[EvidenceChunk] = field(default_factory=list)    # Top matching evidence passages
    verified_claims: List[Any] = field(default_factory=list)     # Claim-level evidence audit records
    abstention_report: Optional[Dict[str, Any]] = None           # Details when abstaining
    citation_report: Optional[Dict[str, Any]] = None             # Comprehensive citation audit details

    def to_dict(self) -> Dict[str, Any]:
        """Converts result object to a dictionary for Streamlit session_state."""
        return {
            "status": self.status,
            "question": self.question,
            "answer": self.answer,
            "confidence": self.confidence,
            "max_score": self.max_score,
            "threshold_used": self.threshold_used,
            "is_abstention": self.is_abstention,
            "reason": self.reason,
            "provider": self.provider,
            "verified_pmids": self.verified_pmids,
            "hallucinated_pmids": self.hallucinated_pmids,
            "papers": self.papers,
            "chunks": self.chunks,
            "verified_claims": [c.to_dict() if hasattr(c, "to_dict") else c for c in self.verified_claims],
            "abstention_report": self.abstention_report,
            "citation_report": self.citation_report,
        }


def run_rag_pipeline(
    question: str,
    max_papers: int = config.DEFAULT_MAX_PAPERS,
    chunk_size: int = config.CHUNK_SIZE_SENTENCES,
    overlap: int = config.CHUNK_OVERLAP_SENTENCES,
    top_k: int = config.TOP_K_CHUNKS,
    threshold: float = config.MIN_SIMILARITY_THRESHOLD,
    retriever: Optional[PubMedRetriever] = None,
    min_year: Optional[int] = None,
    max_year: Optional[int] = None,
) -> Dict[str, Any]:
    """
    Executes the complete RAG pipeline with strict citation validation and abstention guards.
    Applies publication year filtering when min_year or max_year are provided.
    """
    clean_question = question.strip()
    if not clean_question:
        ab_rep = AbstentionReport(
            is_abstained=True,
            search_query="",
            papers_retrieved_count=0,
            reason="No search query provided.",
            additional_research_required="Enter a specific biomedical inquiry."
        )
        return RAGPipelineResult(
            status="error",
            question="",
            answer=config.ABSTENTION_MESSAGE,
            confidence="Insufficient",
            max_score=0.0,
            threshold_used=threshold,
            is_abstention=True,
            reason="Empty question string provided.",
            provider="None",
            abstention_report=ab_rep.to_dict()
        ).to_dict()

    logger.info(f"--- Starting EvidenceBot RAG Pipeline for query: '{clean_question}' ---")

    # -----------------------------------------------------------------
    # Step 1 & 2: PubMed Literature Retrieval
    # -----------------------------------------------------------------
    active_retriever = retriever or PubMedRetriever()
    try:
        search_payload = active_retriever.retrieve(
            clean_question,
            max_results=max_papers,
            min_year=min_year,
            max_year=max_year
        )
    except TypeError:
        # Backward compatibility for mock retrievers in unit tests
        search_payload = active_retriever.retrieve(
            clean_question,
            max_results=max_papers
        )

    # Condition 1: No relevant papers retrieved
    if search_payload.is_empty or not search_payload.papers:
        logger.info(f"PubMed search returned 0 results for '{clean_question}'. Abstaining.")
        ab_rep = evaluate_abstention_triggers(
            search_query=clean_question,
            papers=[],
            chunks=[],
            top_similarity_score=0.0,
            threshold=threshold
        )
        return RAGPipelineResult(
            status="abstained",
            question=clean_question,
            answer=f"**Scientific Abstention: No sufficient scientific evidence found for this query.**\n\n{config.ABSTENTION_MESSAGE}",
            confidence="Insufficient",
            max_score=0.0,
            threshold_used=threshold,
            is_abstention=True,
            reason=ab_rep.reason if ab_rep else "No papers located.",
            provider="None",
            papers=[],
            chunks=[],
            abstention_report=ab_rep.to_dict() if ab_rep else None
        ).to_dict()

    all_retrieved_papers = search_payload.papers

    # -----------------------------------------------------------------
    # Step 3, 4 & 5: Abstract Filtering, Text Cleaning & Chunking
    # -----------------------------------------------------------------
    chunks: List[EvidenceChunk] = chunk_papers(
        all_retrieved_papers,
        chunk_size=chunk_size,
        overlap=overlap
    )

    # Condition 2: Retrieved abstracts do not contain enough information
    if not chunks:
        logger.info("Retrieved papers lacked usable abstract text. Abstaining.")
        ab_rep = evaluate_abstention_triggers(
            search_query=clean_question,
            papers=all_retrieved_papers,
            chunks=[],
            top_similarity_score=0.0,
            threshold=threshold
        )
        return RAGPipelineResult(
            status="abstained",
            question=clean_question,
            answer=f"**Scientific Abstention: No sufficient scientific evidence found for this query.**\n\n{config.ABSTENTION_MESSAGE}",
            confidence="Insufficient",
            max_score=0.0,
            threshold_used=threshold,
            is_abstention=True,
            reason=ab_rep.reason if ab_rep else "Retrieved papers lack abstract content.",
            provider="None",
            papers=all_retrieved_papers,
            chunks=[],
            abstention_report=ab_rep.to_dict() if ab_rep else None
        ).to_dict()

    # -----------------------------------------------------------------
    # Step 6 & 7: Vector Embeddings & In-Memory FAISS Indexing
    # -----------------------------------------------------------------
    vector_store = FaissVectorStore()
    vector_store.add_chunks(chunks)

    # -----------------------------------------------------------------
    # Step 8: Cosine Similarity Retrieval
    # -----------------------------------------------------------------
    retrieved_chunks = vector_store.similarity_search(clean_question, top_k=top_k)

    # -----------------------------------------------------------------
    # Step 9: Irrelevance Filtering & Abstention Guard
    # -----------------------------------------------------------------
    is_sufficient, confidence, reason, max_score, qualifying_chunks = evaluate_evidence_sufficiency(
        retrieved_chunks, threshold=threshold
    )

    # Condition 3: Evidence does not address the question (top similarity < threshold)
    ab_rep = evaluate_abstention_triggers(
        search_query=clean_question,
        papers=all_retrieved_papers,
        chunks=qualifying_chunks,
        top_similarity_score=max_score,
        threshold=threshold
    )

    if ab_rep or not is_sufficient or not qualifying_chunks:
        logger.info(f"Top similarity score ({max_score:.2f}) < threshold ({threshold:.2f}). Triggering Abstention.")
        active_ab_rep = ab_rep or AbstentionReport(
            is_abstained=True,
            search_query=clean_question,
            papers_retrieved_count=len(all_retrieved_papers),
            reason=reason,
            additional_research_required="Targeted clinical trials addressing this specific hypothesis."
        )
        return RAGPipelineResult(
            status="abstained",
            question=clean_question,
            answer=f"**Scientific Abstention: No sufficient scientific evidence found for this query.**\n\n{config.ABSTENTION_MESSAGE}",
            confidence="Insufficient",
            max_score=max_score,
            threshold_used=threshold,
            is_abstention=True,
            reason=active_ab_rep.reason,
            provider="None",
            papers=all_retrieved_papers,
            chunks=retrieved_chunks,
            abstention_report=active_ab_rep.to_dict()
        ).to_dict()

    # -----------------------------------------------------------------
    # Step 10: Grounded Synthesis & Citation Validation
    # -----------------------------------------------------------------
    llm_output = generate_biomedical_answer(clean_question, qualifying_chunks)
    answer_text = llm_output["answer"]
    provider_name = llm_output["provider"]

    # Run comprehensive citation audit
    citation_audit: CitationAuditReport = validate_citations_comprehensive(
        answer_text,
        papers=all_retrieved_papers,
        chunks=qualifying_chunks,
        relevance_threshold=threshold
    )

    # Flag any hallucinated citations
    if citation_audit.hallucinated_pmids:
        logger.warning(f"Detected unverified citations in output: {citation_audit.hallucinated_pmids}")
        answer_text += (
            f"\n\n> ⚠️ **Verification Notice**: The model cited unverified PMID(s): "
            f"`{', '.join(citation_audit.hallucinated_pmids)}`. These have been flagged because they were not in the verified retrieval set."
        )

    # -----------------------------------------------------------------
    # Step 11: Claim-Level Evidence Verification
    # -----------------------------------------------------------------
    logger.info("Performing claim-level evidence verification against retrieved literature...")
    verified_claims = verify_answer_claims(answer_text, qualifying_chunks)

    # Condition 4 & 5: Check if claims are conflicting or unsupported
    post_ab_rep = evaluate_abstention_triggers(
        search_query=clean_question,
        papers=all_retrieved_papers,
        chunks=qualifying_chunks,
        top_similarity_score=max_score,
        threshold=threshold,
        verified_claims=verified_claims
    )

    if post_ab_rep:
        logger.info(f"Post-synthesis abstention triggered: {post_ab_rep.reason}")
        return RAGPipelineResult(
            status="abstained",
            question=clean_question,
            answer=f"**Scientific Abstention: No sufficient scientific evidence found for this query.**\n\n{config.ABSTENTION_MESSAGE}",
            confidence="Insufficient",
            max_score=max_score,
            threshold_used=threshold,
            is_abstention=True,
            reason=post_ab_rep.reason,
            provider=provider_name,
            papers=all_retrieved_papers,
            chunks=qualifying_chunks,
            verified_claims=verified_claims,
            abstention_report=post_ab_rep.to_dict(),
            citation_report=citation_audit.to_dict()
        ).to_dict()

    logger.info(f"RAG synthesis completed successfully with confidence '{confidence}' via {provider_name}.")

    return RAGPipelineResult(
        status="success",
        question=clean_question,
        answer=answer_text,
        confidence=confidence,
        max_score=max_score,
        threshold_used=threshold,
        is_abstention=False,
        reason=reason,
        provider=provider_name,
        verified_pmids=[c.pmid for c in citation_audit.verified_citations],
        hallucinated_pmids=citation_audit.hallucinated_pmids,
        papers=all_retrieved_papers,
        chunks=qualifying_chunks,
        verified_claims=verified_claims,
        abstention_report=None,
        citation_report=citation_audit.to_dict()
    ).to_dict()
